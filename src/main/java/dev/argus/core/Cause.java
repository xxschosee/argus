package dev.argus.core;

/**
 * Причина деградации сервера. Порядок важен: он используется как приоритет
 * при отчёте — сначала то, что бьёт по TPS сильнее всего.
 */
public enum Cause {

    /** TPS просел ниже порога: сервер не успевает за тиками. */
    TPS_DEGRADED,

    /** Среднее время тика выше порога: сервер физически не успевает обрабатывать тик. */
    HIGH_MSPT,

    /** Занятость heap выше порога: сборщик мусора не справляется, начинаются паузы. */
    HEAP_PRESSURE,

    /** Слишком много загруженных сущностей: entity-тик съедает время. */
    ENTITY_OVERLOAD,

    /** Слишком много загруженных чанков: генерация и обновление чанков съедают время. */
    CHUNK_OVERLOAD;

    /** Короткое имя для интерфейса админа и для ключа в конфиге. */
    public String key() {
        return name().toLowerCase(java.util.Locale.ROOT);
    }
}
