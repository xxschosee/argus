package dev.argus.core;

/** Насколько серьёзна проблема. Определяет, лечим ли мы сразу или только сообщаем. */
public enum Severity {

    /** Всё в норме либо проблема незначима. */
    INFO,

    /** Порог предупреждения превышен: лечим мягко, админу сообщаем. */
    WARNING,

    /** Критический порог превышен: лечим и сообщаем в первую очередь. */
    CRITICAL;

    /** Собрать оба порога в одно значение для сравнения: WARNING(1) < CRITICAL(2). */
    public int rank() {
        return ordinal();
    }
}
